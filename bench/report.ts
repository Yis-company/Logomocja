import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { compareRuns } from "../src/benchmark";
import type { RunResult } from "./score";

const percent = (value: number) => `${Math.round(value * 100)}%`;
const seconds = (ms: number) => `${(ms / 1000).toFixed(1)}s`;

/** Renders the markdown summary for a set of run results. */
export function renderSummary(results: RunResult[]): string {
  const sorted = [...results].sort(compareRuns);
  const taskIds = [...new Set(sorted.flatMap((r) => r.tasks.map((t) => t.id)))];
  const lines = [
    "# Benchmark summary",
    "",
    "Generated by `bun bench/report.ts`. One row per run file. Task pass rate counts a sample only when every case passes.",
    "",
    "| Model | Version | Runner | Prompt | Env | Effort | Samples | Tasks | Cases | Mean time | Total time | Started | Note |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ...sorted.map((r) =>
      [
        r.model,
        r.appVersion,
        r.runner,
        r.prompt,
        r.env,
        r.settings.effort ?? "default",
        r.summary.samples,
        percent(r.summary.taskPassRate),
        percent(r.summary.casePassRate),
        seconds(r.summary.meanLatencyMs),
        seconds(r.durationMs),
        r.startedAt.slice(0, 16).replace("T", " "),
        r.partial ? "partial" : "",
      ].join(" | "),
    ).map((row) => `| ${row} |`),
    "",
    "## Per task",
    "",
    "Cases passed out of the task's cases, summed over samples; a failure kind follows when a sample failed.",
    "",
    `| Model | Prompt | Env | ${taskIds.join(" | ")} |`,
    `| --- | --- | --- | ${taskIds.map(() => "---").join(" | ")} |`,
    ...sorted.map((r) => {
      const cells = taskIds.map((id) => {
        const task = r.tasks.find((t) => t.id === id);
        if (!task?.samples.length) return "—";
        const passed = task.samples.reduce((sum, s) => sum + s.casesPassed, 0);
        const total = task.samples.reduce((sum, s) => sum + s.casesTotal, 0);
        const kinds = [...new Set(task.samples.flatMap((s) => (s.failure ? [s.failure.kind] : [])))];
        return `${passed}/${total}${kinds.length ? ` ${kinds.join(",")}` : ""}`;
      });
      return `| ${r.model} | ${r.prompt} | ${r.env} | ${cells.join(" | ")} |`;
    }),
    "",
  ];
  return lines.join("\n");
}

export function readResults(dir: string): RunResult[] {
  return readdirSync(dir)
    .filter((name) => name.endsWith(".json"))
    .sort()
    .map((name) => JSON.parse(readFileSync(join(dir, name), "utf8")) as RunResult);
}

if (import.meta.main) {
  const dir = fileURLToPath(new URL("./results/", import.meta.url));
  const results = readResults(dir);
  writeFileSync(join(dir, "SUMMARY.md"), renderSummary(results));
  console.log(`${results.length} runs -> ${join(dir, "SUMMARY.md")}`);
}
